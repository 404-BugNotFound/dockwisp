import assert from "node:assert/strict";
import test from "node:test";
import {
  isShellAppPath,
  isUwpAppId,
  linkIdentity,
  parseStartApps,
  pickIconVariant,
  resolveKnownFolderPath,
  shellAppPath,
  shellAppTarget,
} from "../src/core/start-apps";

test("parseStartApps normalises array, single-object and null shapes", () => {
  const array = parseStartApps(
    JSON.stringify([
      { Name: "计算器", AppID: "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App" },
      { Name: "7-Zip", AppID: "{6D809377-6AF0-444B-8957-A3773F02200E}\\7-Zip\\7zFM.exe" },
    ]),
  );
  assert.equal(array.length, 2);
  assert.equal(array[0].name, "计算器");
  assert.equal(array[0].appId, "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App");

  const single = parseStartApps(JSON.stringify({ Name: "Solo", AppID: "Solo!App" }));
  assert.deepEqual(single, [{ name: "Solo", appId: "Solo!App" }]);

  assert.deepEqual(parseStartApps("null"), []);
  assert.deepEqual(parseStartApps("not json"), []);
});

test("parseStartApps drops entries without a name or app id and keeps icon data", () => {
  const apps = parseStartApps(
    JSON.stringify([
      { Name: "", AppID: "x!y" },
      { Name: "No Id" },
      {
        Name: "Calc",
        AppID: "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App",
        InstallLocation: "C:\\Program Files\\WindowsApps\\Calc",
        Logo: "Assets\\CalculatorAppList.png",
      },
    ]),
  );
  assert.equal(apps.length, 1);
  assert.equal(apps[0].installLocation, "C:\\Program Files\\WindowsApps\\Calc");
  assert.equal(apps[0].logo, "Assets\\CalculatorAppList.png");
});

test("parseStartApps keeps auto-generated shortcut target and arguments", () => {
  const [app] = parseStartApps(
    JSON.stringify({
      Name: "资源监视器",
      AppID: "Microsoft.AutoGenerated.{8B5B34DF-CB74-294D-5DE2-53C565924C57}",
      Target: "C:\\WINDOWS\\system32\\perfmon.exe",
      Arguments: "/res",
    }),
  );
  assert.equal(app.target, "C:\\WINDOWS\\system32\\perfmon.exe");
  assert.equal(app.arguments, "/res");
});

test("linkIdentity matches the same target and arguments case-insensitively", () => {
  assert.equal(
    linkIdentity("C:\\WINDOWS\\system32\\perfmon.exe", "/res"),
    linkIdentity("c:\\Windows\\System32\\PERFMON.EXE", " /RES "),
  );
  assert.notEqual(
    linkIdentity("C:\\WINDOWS\\system32\\perfmon.exe", "/res"),
    linkIdentity("C:\\WINDOWS\\system32\\perfmon.exe", "/s"),
  );
  assert.notEqual(
    linkIdentity("C:\\WINDOWS\\system32\\perfmon.exe"),
    linkIdentity("C:\\WINDOWS\\system32\\perfmon.exe", "/res"),
  );
});

test("shell app path helpers round-trip and detect shell paths", () => {
  const appId = "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App";
  const shellPath = shellAppPath(appId);
  assert.equal(shellPath, "shell:AppsFolder\\Microsoft.WindowsCalculator_8wekyb3d8bbwe!App");
  assert.equal(isShellAppPath(shellPath), true);
  assert.equal(isShellAppPath("C:\\Windows\\notepad.exe"), false);
  assert.equal(shellAppTarget(shellPath), appId);
  assert.equal(shellAppTarget("C:\\Windows\\notepad.exe"), "");
});

test("isUwpAppId distinguishes UWP ids from shell/path ids", () => {
  assert.equal(isUwpAppId("Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"), true);
  assert.equal(isUwpAppId("{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\\cmd.exe"), false);
  assert.equal(isUwpAppId("Microsoft.AutoGenerated.{GUID}"), false);
});

test("resolveKnownFolderPath resolves known GUIDs via the supplied env", () => {
  const env = {
    SystemRoot: "C:\\Windows",
    "ProgramFiles(x86)": "C:\\Program Files (x86)",
    ProgramW6432: "C:\\Program Files",
  };
  assert.equal(
    resolveKnownFolderPath("{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\\cmd.exe", env),
    "C:\\Windows\\System32\\cmd.exe",
  );
  assert.equal(
    resolveKnownFolderPath("{D65231B0-B2F1-4857-A4CE-A8E7C6EA7D27}\\cmd.exe", env),
    "C:\\Windows\\SysWOW64\\cmd.exe",
  );
  assert.equal(
    resolveKnownFolderPath("{F38BF404-1D43-42F2-9305-67DE0B28FC23}\\explorer.exe", env),
    "C:\\Windows\\explorer.exe",
  );
  assert.equal(
    resolveKnownFolderPath("{6D809377-6AF0-444B-8957-A3773F02200E}\\7-Zip\\7zFM.exe", env),
    "C:\\Program Files\\7-Zip\\7zFM.exe",
  );
  assert.equal(
    resolveKnownFolderPath("{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\\app.exe", env),
    "C:\\Program Files (x86)\\app.exe",
  );
});

test("resolveKnownFolderPath returns null for unknown GUIDs, UWP and missing env", () => {
  assert.equal(resolveKnownFolderPath("Microsoft.WindowsCalculator_x!App", {}), null);
  assert.equal(resolveKnownFolderPath("{00000000-0000-0000-0000-000000000000}\\x.exe", {}), null);
  assert.equal(
    resolveKnownFolderPath("{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\\cmd.exe", {}),
    null,
  );
});

test("pickIconVariant favours an unplated target-size asset nearest 48px", () => {
  const files = [
    "CalculatorAppList.scale-200.png",
    "CalculatorAppList.scale-200_contrast-black.png",
    "CalculatorAppList.targetsize-16.png",
    "CalculatorAppList.targetsize-48_altform-unplated.png",
    "CalculatorAppList.targetsize-48.png",
    "CalculatorAppList.targetsize-256.png",
    "OtherApp.targetsize-48.png",
  ];
  assert.equal(
    pickIconVariant("Assets\\CalculatorAppList.png", files),
    "CalculatorAppList.targetsize-48_altform-unplated.png",
  );
});

test("pickIconVariant falls back to scale then plain, and ignores contrast-only sets", () => {
  assert.equal(
    pickIconVariant("Assets\\Logo.png", ["Logo.scale-100.png", "Logo.scale-200.png"]),
    "Logo.scale-200.png",
  );
  assert.equal(pickIconVariant("Assets\\Logo.png", ["Logo.png"]), "Logo.png");
  assert.equal(
    pickIconVariant("Assets\\Logo.png", ["Logo.scale-200_contrast-white.png"]),
    null,
  );
  assert.equal(pickIconVariant("Assets\\Logo.png", ["Unrelated.png"]), null);
});
